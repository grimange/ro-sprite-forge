"""Versioned operator declarations and deterministic reuse dependencies (RSF-9).

No image processing or artistic evaluation. Bytes and local paths stay outside
contracts. Review records are operator assertions, never generated by this module.
"""
from collections import deque
from importlib.resources import files
import json
from dataclasses import dataclass
from typing import Mapping

from ro_sprite_forge.core.canonical import canonical_bytes, check_seal, digest, sealed
from ro_sprite_forge.core.contracts import Contract, _shape, require

MAX_RECORDS = 100000
MAX_SOURCE_BYTES = 64 * 1024 * 1024
MAX_RESOLVED_STEPS = 1000000


def ledger_schema() -> dict:
    return json.loads(files('ro_sprite_forge').joinpath('schemas/assignment-ledger-v1.json').read_text())


@dataclass(frozen=True)
class AssignmentLedger(Contract):
    """Immutable declaration; observations live in a separate sealed report."""


def composition_target(requirements, layer):
    """Opt-in action-local identity excludes unrelated action revisions, never actor/profile changes."""
    if layer.get('action_basis'):
        return dict(id=requirements['target']['id'], revision=1, canonical_sha256=layer['action_basis'])
    return requirements['target']


def assignment_binding(layer: dict) -> dict:
    return {k: layer[v] for k, v in (('part', 'part'), ('action', 'action'),
        ('view', 'view'), ('frame', 'frame'), ('layer', 'ordinal'))}


def _requirements(value: dict) -> dict:
    check_seal(value, 'rsf.resolved-requirements/v1')
    for field in ('target', 'runtime_profile'):
        require(type(value.get(field)) is dict and
                {'id', 'canonical_sha256'} <= value[field].keys(),
                '/' + field, 'Invalid resolved contract reference.')
    require(type(value.get('slots')) is list and len(value['slots']) <= MAX_RECORDS,
            '/slots', 'Invalid resolved slot list.')
    slots = set()
    for i, slot in enumerate(value['slots']):
        require(type(slot) is dict and type(slot.get('id')) is str and
                slot.get('runtime_mapping') in ('SUPPORTED', 'UNSUPPORTED', 'UNVERIFIED'),
                f'/slots/{i}', 'Invalid resolved slot.')
        require(slot['id'] not in slots, f'/slots/{i}/id', 'Duplicate slot.')
        slots.add(slot['id'])
    require(type(value.get('layers')) is list and len(value['layers']) <= MAX_RECORDS,
            '/layers', 'REQUIREMENT_BUDGET: invalid layer list.')
    layers = {}
    for i, layer in enumerate(value['layers']):
        require(type(layer) is dict and type(layer.get('id')) is str,
                f'/layers/{i}', 'Invalid resolved requirement.')
        require(layer['id'] not in layers, f'/layers/{i}/id', 'Duplicate requirement.')
        require(type(layer.get('frame_id')) is str and
                layer['frame_id'].rsplit('/frame', 1)[0] in slots,
                f'/layers/{i}/frame_id', 'Invalid frame/slot reference.')
        require(all(type(layer.get(k)) is str for k in ('part', 'action')) and
                all(type(layer.get(k)) is int and layer[k] >= 0 for k in ('view', 'frame', 'ordinal')) and
                layer.get('requirement') in ('REQUIRED', 'OPTIONAL'),
                f'/layers/{i}', 'Invalid resolved layer binding.')
        layers[layer['id']] = layer
    return layers


def _order(assignments: dict, attachments: list | None = None) -> list[str]:
    """Iterative deterministic dependency-first order; bounded, no Python recursion."""
    children = {key: [] for key in assignments}
    indegree = {key: 0 for key in assignments}
    for key, item in assignments.items():
        dep = item['dependency']
        if dep is not None:
            require(dep['id'] in assignments, f'/assignments/{key}/dependency',
                    'MISSING_DEPENDENCY: ' + dep['id'])
            require(assignments[dep['id']]['revision'] == dep['revision'],
                    f'/assignments/{key}/dependency/revision', 'STALE_DEPENDENCY_REVISION.')
            children[dep['id']].append(key)
            indegree[key] += 1
    for link in attachments or []:
        parent, child = link['parent_assignment'], link['child_assignment']
        if child not in children[parent]:
            children[parent].append(child)
            indegree[child] += 1
    ready = deque(sorted(k for k, n in indegree.items() if n == 0))
    result = []
    while ready:
        key = ready.popleft()
        result.append(key)
        for child in sorted(children[key]):
            indegree[child] -= 1
            if not indegree[child]:
                ready.append(child)
    remaining = sorted(k for k, n in indegree.items() if n)
    require(not remaining, '/assignments', 'CYCLIC_REUSE: ' + ', '.join(remaining))
    return result


def load_ledger(value: dict, *, requirements: dict,
                previous: AssignmentLedger | None = None) -> AssignmentLedger:
    """Validate declarations, exact target binding and dependency graph, then seal.

    A stale ledger is rejected here; compare_ledgers can preserve/report its old
    assignments against a newly resolved target without silently migrating them.
    """
    _shape(value, ledger_schema())
    if 'canonical_sha256' in value:
        require(value['canonical_sha256'] == digest(canonical_bytes({k:v for k,v in value.items() if k != 'canonical_sha256'})),
                '/canonical_sha256', 'Canonical digest mismatch.')
    payload = json.loads(canonical_bytes({k: v for k, v in value.items() if k != 'canonical_sha256'}))
    layers = _requirements(requirements)
    require(value['target'] == requirements['target'], '/target', 'STALE_TARGET_REVISION_OR_IDENTITY.')
    require(value['requirements_sha256'] == requirements['canonical_sha256'],
            '/requirements_sha256', 'CHANGED_REQUIREMENTS: explicit rebinding required.')
    for field in ('sources', 'assignments', 'attachments'):
        ids = [i['id'] for i in value[field]]
        require(len(ids) == len(set(ids)), '/' + field, 'DUPLICATE_IDENTITY.')
        payload[field].sort(key=lambda x: x['id'])
    sources = {s['id']: s for s in payload['sources']}
    assignments = {a['id']: a for a in payload['assignments']}
    for sid, source in sources.items():
        if source['kind'] == 'IMPORTED_IMAGE':
            require(source['image'] is not None and source['provenance'] is not None,
                    '/sources/' + sid, 'IMPORTED_IMAGE_REQUIRES_POOL_AND_PROVENANCE.')
    bound = set()
    for i, item in enumerate(payload['assignments']):
        path = f'/assignments/{i}'
        rid = item['requirement_id']
        require(rid in layers, path + '/requirement_id', 'NONEXISTENT_REQUIREMENT: ' + rid)
        require(rid not in bound, path + '/requirement_id', 'DUPLICATE_ASSIGNMENT.')
        bound.add(rid)
        require(item['binding'] == assignment_binding(layers[rid]), path + '/binding', 'REQUIREMENT_BINDING_MISMATCH.')
        kind, source, dep = item['kind'], item['source'], item['dependency']
        require((kind == 'DIRECT_SOURCE' and source is not None and dep is None) or
                (kind == 'EXPLICIT_REUSE' and source is None and dep is not None) or
                (kind == 'UNASSIGNED' and source is None and dep is None and not item['recipe'] and item['review'] is None),
                path + '/kind', 'CONFLICTING_ASSIGNMENT_DECLARATION.')
        if source is not None:
            require(source['id'] in sources, path + '/source', 'MISSING_SOURCE_DECLARATION.')
            require(sources[source['id']]['revision'] == source['revision'], path + '/source/revision', 'STALE_SOURCE_REVISION.')
        opids = [o['id'] for o in item['recipe']]
        require(len(opids) == len(set(opids)), path + '/recipe', 'DUPLICATE_OPERATION: array order must be unambiguous.')
        review = item['review']
        if review is not None:
            require((review['state'] == 'NOT_REQUIRED') == (review['policy'] == 'UNCHANGED_REFERENCE'),
                    path + '/review/policy', 'NOT_REQUIRED needs explicit unchanged-reference policy.')
    _order(assignments)
    child_ids = set()
    for i, link in enumerate(payload['attachments']):
        path = f'/attachments/{i}'
        parent, child = link['parent_assignment'], link['child_assignment']
        require(parent in assignments and child in assignments and parent != child,
                path, 'INVALID_ATTACHMENT_REFERENCE.')
        require(child not in child_ids, path + '/child_assignment', 'CONFLICTING_ATTACHMENT_PARENT.')
        child_ids.add(child)
        pb, cb = assignments[parent]['binding'], assignments[child]['binding']
        require(pb['part'] == link['parent_part'] and cb['part'] == link['child_part'] and pb['part'] != cb['part'],
                path, 'ATTACHMENT_PART_MISMATCH.')
        require(all(pb[k] == cb[k] for k in ('action', 'view', 'frame')), path, 'ATTACHMENT_FRAME_MAPPING_MISMATCH.')
    # Attachments are a separate parent graph; forbid cycles and preserve explicit anchors.
    parents = {x['child_assignment']: x['parent_assignment'] for x in payload['attachments']}
    done = set()
    for start in sorted(parents):
        trail, node = set(), start
        while node in parents and node not in done:
            require(node not in trail, '/attachments', 'CYCLIC_ATTACHMENT: ' + ', '.join(sorted(trail)))
            trail.add(node); node = parents[node]
        done.update(trail)
    _order(assignments, payload['attachments'])
    result = AssignmentLedger(canonical_bytes(sealed(payload)))
    if previous is not None:
        old = previous.to_dict()
        require(value['id'] == old['id'], '/id', 'Ledger identity cannot change across revisions.')
        if result.canonical_sha256 != previous.canonical_sha256:
            require(value['revision'] > old['revision'] and value['previous_sha256'] == previous.canonical_sha256,
                    '/revision', 'CHANGED_LEDGER_REQUIRES_LINKED_REVISION.')
            for field in ('sources', 'assignments'):
                prior = {r['id']: r for r in old[field]}
                for row in payload[field]:
                    if row['id'] in prior and row != prior[row['id']]:
                        require(row['revision'] > prior[row['id']]['revision'], '/' + field + '/' + row['id'] + '/revision',
                                'CHANGED_RECORD_REQUIRES_REVISION.')
    elif value['revision'] == 1:
        require(value['previous_sha256'] is None, '/previous_sha256', 'First revision has no predecessor.')
    return result


def resolve_ledger(ledger: AssignmentLedger, *, requirements: dict,
                   source_bytes: Mapping[str, bytes | None] | None = None) -> dict:
    """Observe content hashes and resolve recipes; never execute or visually approve.

    Unprovided ID => UNVERIFIED; explicit None => MISSING. Bytes verify only
    content identity, not PNG decoding or artistic constraints. Reuse is accepted
    only when every edge/root has an applicable explicit operator review binding.
    """
    value = ledger.to_dict()
    # Revalidate even if constructed through the public dataclass constructor.
    load_ledger(value, requirements=requirements)
    layers = _requirements(requirements)
    sources = {s['id']: s for s in value['sources']}
    data = {} if source_bytes is None else source_bytes
    require(set(data) <= sources.keys(), '/source_bytes', 'UNKNOWN_SOURCE_BYTES_ID.')
    require(sum(len(b) for b in data.values() if isinstance(b, bytes)) <= MAX_SOURCE_BYTES,
            '/source_bytes', 'SOURCE_BYTE_BUDGET_EXCEEDED.')
    observations = {}
    for sid, source in sorted(sources.items()):
        availability, validation, actual, code = 'UNVERIFIED', 'UNVERIFIED', None, None
        if sid in data:
            content = data[sid]
            require(content is None or type(content) is bytes, '/source_bytes/' + sid, 'Expected bytes or explicit missing None.')
            if content is None:
                availability, code = 'MISSING', 'SOURCE_UNAVAILABLE'
            else:
                availability, actual = 'AVAILABLE', digest(content)
                if source['sha256'] is None:
                    code = 'SOURCE_HASH_UNDECLARED'
                elif actual != source['sha256']:
                    validation, code = 'INVALID', 'SOURCE_HASH_MISMATCH'
                elif not content:
                    validation, code = 'INVALID', 'EMPTY_SOURCE'
                else:
                    validation = 'VALID'
        observations[sid] = {'id': sid, 'revision': source['revision'], 'declared_sha256': source['sha256'],
            'actual_sha256': actual, 'availability': availability, 'validation': validation, 'diagnostic': code,
            'constraint_scope': 'NONEMPTY_CONTENT_HASH_ONLY', 'image_decode': 'NOT_RUN'}
    assignments = {a['id']: a for a in value['assignments']}
    results, budget = {}, 0
    links = {x['child_assignment']: x for x in value['attachments']}
    slot_map = {s['id']: s for s in requirements['slots']}
    for aid in _order(assignments, value['attachments']):
        item = assignments[aid]
        dep = results[item['dependency']['id']] if item['dependency'] else None
        source = sources[item['source']['id']] if item['source'] else (dep['effective_source'] if dep else None)
        chain = (dep['transform_chain'] if dep else []) + [
            {'assignment': {'id': aid, 'revision': item['revision']}, 'operation': op} for op in item['recipe']]
        lineage = (dep['lineage'] if dep else []) + [{'id': aid, 'revision': item['revision']}]
        budget += len(chain) + len(lineage)
        require(budget <= MAX_RESOLVED_STEPS, '/assignments', 'RESOLUTION_BUDGET_EXCEEDED.')
        obs = observations[source['id']] if source is not None else None
        slot = slot_map[layers[item['requirement_id']]['frame_id'].rsplit('/frame', 1)[0]]
        basis = digest(canonical_bytes({'schema': 'rsf.assignment-review-basis/v1',
            'target': composition_target(requirements, layers[item['requirement_id']]), 'runtime_profile': requirements['runtime_profile'],
            'requirement': layers[item['requirement_id']], 'assignment': {k:v for k,v in item.items() if k != 'review'},
            'source': source, 'dependency_basis': dep['composition_sha256'] if dep else None,
            'attachment': links.get(aid),
            'attachment_parent_basis': results[links[aid]['parent_assignment']]['composition_sha256'] if aid in links else None}))
        review = item['review']
        visual, review_state = 'UNVERIFIED', 'UNRECORDED'
        if review is not None:
            if review['basis_sha256'] != basis:
                review_state = 'STALE'
            elif review['state'] == 'NOT_REQUIRED' and (source is None or source['origin'] != 'CLASSIC_REFERENCE' or chain):
                review_state = 'INAPPLICABLE_POLICY'
            else:
                visual, review_state = review['state'], 'BOUND_OPERATOR_DECLARATION'
        valid = obs['validation'] if obs else 'UNVERIFIED'
        available = obs['availability'] if obs else 'MISSING'
        if dep is not None:
            valid = dep['validation']
            available = 'REUSED' if dep['availability'] in ('AVAILABLE', 'REUSED') else dep['availability']
        accepted = bool(source is not None and valid == 'VALID' and available in ('AVAILABLE', 'REUSED')
                        and visual in ('APPROVED', 'NOT_REQUIRED') and (dep is None or dep['reuse_accepted']))
        results[aid] = {'id': aid, 'revision': item['revision'], 'requirement_id': item['requirement_id'],
            'requirement_sha256': digest(canonical_bytes(layers[item['requirement_id']])),
            'kind': item['kind'], 'effective_source': source, 'root_assignment': dep['root_assignment'] if dep else aid,
            'lineage': lineage, 'transform_chain': chain, 'composition_sha256': basis,
            'availability': available, 'validation': valid, 'visual_review': visual,
            'review_binding': review_state, 'reuse_accepted': accepted,
            'runtime_support': slot['runtime_mapping'], 'native_evidence': 'UNVERIFIED',
            'source_origin': source['origin'] if source else None,
            'replacement_artwork': bool(accepted and source['origin'] == 'AUTHORED'),
            'transforms_executed': False}
    by_requirement = {r['requirement_id']: r for r in results.values()}
    occurrences = []
    for rid, layer in sorted(layers.items()):
        row = by_requirement.get(rid)
        occurrences.append({'requirement_id': rid, 'binding': assignment_binding(layer),
            'assignment_id': row['id'] if row else None,
            'kind': row['kind'] if row else 'UNASSIGNED',
            'availability': row['availability'] if row else 'MISSING',
            'validation': row['validation'] if row else 'UNVERIFIED',
            'visual_review': row['visual_review'] if row else 'UNVERIFIED'})
    return sealed({'schema': 'rsf.resolved-ledger/v1', 'ledger_sha256': ledger.canonical_sha256,
        'target': value['target'], 'requirements_sha256': requirements['canonical_sha256'],
        'sources': list(observations.values()), 'assignments': [results[k] for k in sorted(results)],
        'occurrences': occurrences, 'attachments': value['attachments'],
        'edges': [{'dependency': a['dependency']['id'], 'dependent': a['id']} for a in value['assignments'] if a['dependency']],
        'counts': {'known_layers': len(layers), 'required_layers_known': sum(l['requirement'] == 'REQUIRED' for l in layers.values()), 'selected_assignments': sum(r['kind'] != 'UNASSIGNED' for r in results.values()),
            'unassigned': sum(o['kind'] == 'UNASSIGNED' for o in occurrences),
            'direct': sum(r['kind'] == 'DIRECT_SOURCE' for r in results.values()),
            'explicit_reuse': sum(r['kind'] == 'EXPLICIT_REUSE' for r in results.values()),
            'accepted_reuse': sum(r['kind'] == 'EXPLICIT_REUSE' and r['reuse_accepted'] for r in results.values()),
            'approved_source_art_roots': len({r['root_assignment'] for r in results.values() if r['replacement_artwork']}),
            'validated_replacement_occurrences': sum(r['replacement_artwork'] for r in results.values())},
        'status': {'artwork_effort': 'PARTIAL_EXPLICIT_APPROVED_ROOTS_ONLY',
                   'coverage_evaluation': 'NOT_RUN', 'export_ready': False,
                   'visual_approval_authority': 'OPERATOR_ONLY'}})


def _validate_resolved_report(report: dict) -> None:
    """Validate external impact inputs; a content seal is not a shape guarantee."""
    check_seal(report, 'rsf.resolved-ledger/v1')
    declaration = ledger_schema()['properties']
    source_rule = declaration['sources']['items']
    assignment_rule = declaration['assignments']['items']['properties']
    ident = declaration['id']
    sha = declaration['requirements_sha256']
    nullable_sha = declaration['previous_sha256']
    revision = declaration['revision']
    def obj(fields):
        return {'type': 'object', 'required': list(fields), 'properties': fields}
    def array(item, maximum=MAX_RECORDS):
        return {'type': 'array', 'minItems': 0, 'maxItems': maximum, 'items': item}
    def enum(*values):
        return {'enum': list(values)}
    availability = enum('AVAILABLE', 'REUSED', 'MISSING', 'UNVERIFIED')
    validity = enum('VALID', 'INVALID', 'UNVERIFIED')
    visual = enum('APPROVED', 'REJECTED', 'UNVERIFIED', 'NOT_REQUIRED')
    boolean = enum(True, False)
    reference = obj({'id': ident, 'revision': revision})
    rid = assignment_rule['requirement_id']
    resolved_assignment = obj({
        'id': ident, 'revision': revision, 'requirement_id': rid, 'requirement_sha256': sha,
        'kind': assignment_rule['kind'], 'effective_source': {'anyOf': [{'type': 'null'}, source_rule]},
        'root_assignment': ident, 'lineage': array(reference),
        'transform_chain': array(obj({'assignment': reference,
            'operation': assignment_rule['recipe']['items']}), MAX_RESOLVED_STEPS),
        'composition_sha256': sha, 'availability': availability, 'validation': validity,
        'visual_review': visual, 'review_binding': enum('UNRECORDED', 'STALE', 'INAPPLICABLE_POLICY', 'BOUND_OPERATOR_DECLARATION'),
        'reuse_accepted': boolean, 'runtime_support': enum('SUPPORTED', 'UNSUPPORTED', 'UNVERIFIED'),
        'native_evidence': enum('UNVERIFIED'),
        'source_origin': enum(None, 'AUTHORED', 'CLASSIC_REFERENCE', 'UNVERIFIED'),
        'replacement_artwork': boolean, 'transforms_executed': enum(False)})
    observation = obj({'id': ident, 'revision': revision, 'declared_sha256': nullable_sha,
        'actual_sha256': nullable_sha, 'availability': enum('AVAILABLE', 'MISSING', 'UNVERIFIED'),
        'validation': validity, 'diagnostic': enum(None, 'SOURCE_UNAVAILABLE', 'SOURCE_HASH_UNDECLARED',
            'SOURCE_HASH_MISMATCH', 'EMPTY_SOURCE'),
        'constraint_scope': enum('NONEMPTY_CONTENT_HASH_ONLY'), 'image_decode': enum('NOT_RUN')})
    count = {'type': 'integer', 'minimum': 0, 'maximum': MAX_RECORDS}
    _shape(report, obj({'schema': enum('rsf.resolved-ledger/v1'), 'canonical_sha256': sha,
        'ledger_sha256': sha, 'target': declaration['target'], 'requirements_sha256': sha,
        'sources': array(observation, 10000), 'assignments': array(resolved_assignment),
        'occurrences': array(obj({'requirement_id': rid, 'binding': assignment_rule['binding'],
            'assignment_id': {'anyOf': [{'type': 'null'}, ident]}, 'kind': assignment_rule['kind'],
            'availability': availability, 'validation': validity, 'visual_review': visual})),
        'attachments': declaration['attachments'],
        'edges': array(obj({'dependency': ident, 'dependent': ident})),
        'counts': obj({key: count for key in ('known_layers', 'required_layers_known', 'selected_assignments',
            'unassigned', 'direct', 'explicit_reuse', 'accepted_reuse', 'approved_source_art_roots',
            'validated_replacement_occurrences')}),
        'status': obj({'artwork_effort': enum('PARTIAL_EXPLICIT_APPROVED_ROOTS_ONLY'),
            'coverage_evaluation': enum('NOT_RUN'), 'export_ready': enum(False),
            'visual_approval_authority': enum('OPERATOR_ONLY')})}))
    indexed = {}
    for field, key in (('sources', 'id'), ('assignments', 'id'), ('attachments', 'id'), ('occurrences', 'requirement_id')):
        rows = report[field]
        indexed[field] = {row[key]: row for row in rows}
        require(len(indexed[field]) == len(rows), '/' + field, 'DUPLICATE_REPORT_IDENTITY.')
    assignments, sources, occurrences = indexed['assignments'], indexed['sources'], indexed['occurrences']
    proxies = {aid: {'revision': a['revision'], 'dependency': None} for aid, a in assignments.items()}
    for i, edge in enumerate(report['edges']):
        parent, child = edge['dependency'], edge['dependent']
        require(parent in assignments and child in assignments, f'/edges/{i}', 'MISSING_REPORT_DEPENDENCY.')
        require(assignments[child]['kind'] == 'EXPLICIT_REUSE' and proxies[child]['dependency'] is None,
                f'/edges/{i}', 'CONFLICTING_REPORT_DEPENDENCY.')
        proxies[child]['dependency'] = {'id': parent, 'revision': assignments[parent]['revision']}
    steps = 0
    for aid, item in assignments.items():
        path = '/assignments/' + aid
        require((item['kind'] == 'EXPLICIT_REUSE') == (proxies[aid]['dependency'] is not None),
                path, 'MISSING_REPORT_DEPENDENCY.')
        rid_value = item['requirement_id']
        require(rid_value in occurrences and occurrences[rid_value]['assignment_id'] == aid,
                path + '/requirement_id', 'INVALID_REPORT_REQUIREMENT_BINDING.')
        require(item['root_assignment'] in assignments, path + '/root_assignment', 'MISSING_REPORT_ROOT.')
        source = item['effective_source']
        require(source is None or (source['id'] in sources and source['revision'] == sources[source['id']]['revision']
                and source['sha256'] == sources[source['id']]['declared_sha256']),
                path + '/effective_source', 'INVALID_REPORT_SOURCE_REFERENCE.')
        steps += len(item['lineage']) + len(item['transform_chain'])
        require(steps <= MAX_RESOLVED_STEPS, path, 'RESOLUTION_BUDGET_EXCEEDED.')
        for ref in item['lineage'] + [step['assignment'] for step in item['transform_chain']]:
            require(ref['id'] in assignments and ref['revision'] == assignments[ref['id']]['revision'],
                    path, 'INVALID_REPORT_LINEAGE_REFERENCE.')
    for rid_value, row in occurrences.items():
        aid = row['assignment_id']
        require((aid is None and row['kind'] == 'UNASSIGNED') or
                (aid in assignments and assignments[aid]['requirement_id'] == rid_value and
                 row['kind'] == assignments[aid]['kind']),
                '/occurrences/' + rid_value, 'INVALID_REPORT_ASSIGNMENT_REFERENCE.')
    child_ids = set()
    for i, link in enumerate(report['attachments']):
        parent, child = link['parent_assignment'], link['child_assignment']
        path = f'/attachments/{i}'
        require(parent in assignments and child in assignments and parent != child,
                path, 'INVALID_ATTACHMENT_REFERENCE.')
        require(child not in child_ids, path, 'CONFLICTING_ATTACHMENT_PARENT.')
        child_ids.add(child)
        p = occurrences[assignments[parent]['requirement_id']]['binding']
        c = occurrences[assignments[child]['requirement_id']]['binding']
        require(p['part'] == link['parent_part'] and c['part'] == link['child_part'] and p['part'] != c['part']
                and all(p[k] == c[k] for k in ('action', 'view', 'frame')),
                path, 'ATTACHMENT_BINDING_MISMATCH.')
    _order(proxies, report['attachments'])


def compare_ledgers(before: dict, after: dict, *, current_requirements: dict | None = None) -> dict:
    """Dependency closure of changed declarations/observations, without migration.

    Reports old IDs orphaned by a target change; never guesses replacement IDs.
    Review/display evidence changes alone do not alter the composition basis.
    """
    for report in (before, after):
        _validate_resolved_report(report)
    old = {a['id']: a for a in before['assignments']}
    new = {a['id']: a for a in after['assignments']}
    reasons = {}
    for aid in sorted(old.keys() | new.keys()):
        a, b = old.get(aid), new.get(aid)
        changed = []
        if a is None or b is None:
            changed.append('ASSIGNMENT_ADDED' if a is None else 'ASSIGNMENT_REMOVED')
        else:
            for field, code in (('composition_sha256','COMPOSITION_CHANGED'), ('availability','SOURCE_AVAILABILITY_CHANGED'),
                    ('validation','SOURCE_VALIDATION_CHANGED')):
                if a[field] != b[field]: changed.append(code)
        if changed: reasons[aid] = changed
    # Hash changes must be detected even when both the old/new bytes mismatch.
    os = {s['id']: s for s in before['sources']}; ns = {s['id']: s for s in after['sources']}
    changed_sources = {sid for sid in os.keys() | ns.keys() if os.get(sid) != ns.get(sid)}
    for aid in sorted(old.keys() | new.keys()):
        if any(r and r['effective_source'] and r['effective_source']['id'] in changed_sources for r in (old.get(aid),new.get(aid))):
            reasons.setdefault(aid, []).append('SOURCE_EVIDENCE_CHANGED')
    children = {}
    for edge in before['edges'] + after['edges']:
        children.setdefault(edge['dependency'], set()).add(edge['dependent'])
    # Attachment parent changes affect the child even without a reuse edge.
    for link in before['attachments'] + after['attachments']:
        children.setdefault(link['parent_assignment'], set()).add(link['child_assignment'])
    affected = set(reasons); todo = deque(sorted(affected))
    while todo:
        for child in sorted(children.get(todo.popleft(), ())):
            if child not in affected:
                affected.add(child); todo.append(child)
    orphaned = []
    if current_requirements is not None:
        current = _requirements(current_requirements)
        orphaned = sorted(aid for aid, a in old.items() if a['requirement_id'] not in current)
        for aid in orphaned:
            reasons.setdefault(aid, []).append('ORPHANED_REQUIREMENT')
        stale = []
        for aid, a in sorted(old.items()):
            if a['requirement_id'] in current and digest(canonical_bytes(current[a['requirement_id']])) != a['requirement_sha256']:
                stale.append(aid)
                reasons.setdefault(aid, []).append('REQUIREMENT_CHANGED')
            elif before['target'] != current_requirements['target']:
                stale.append(aid)
                reasons.setdefault(aid, []).append('STALE_TARGET_REVISION')
        # Orphans also invalidate their dependency closure.
        todo = deque(orphaned + stale); affected.update(orphaned + stale)
        while todo:
            for child in sorted(children.get(todo.popleft(), ())):
                if child not in affected: affected.add(child); todo.append(child)
    return sealed({'schema': 'rsf.ledger-impact/v1', 'before_sha256': before['canonical_sha256'],
        'after_sha256': after['canonical_sha256'], 'changed_sources': sorted(changed_sources),
        'changed_assignments': [{'id': k, 'reasons': sorted(set(v))} for k,v in sorted(reasons.items())],
        'affected_assignments': sorted(affected), 'unaffected_assignments': sorted((old.keys() | new.keys()) - affected),
        'orphaned_assignments': orphaned, 'review_action': 'REVIEW_BASIS_RECHECK_REQUIRED_NO_AUTO_APPROVAL'})
