#!/usr/bin/env python3
"""Materialize a bounded native presentation build from immutable Korangar Git objects.

Never edits the supplied checkout. Selection, preparation and GPU draw algorithms
are imported verbatim; UI derives and unused UI/gameplay modules are omitted.
The manifest records both upstream and generated bytes for independent review.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

REVISION = "3f3d88a583203f09d079712f43343c1041258ffd"
HERE = Path(__file__).resolve().parent


def block(text, start):
    begin = text.index(start)
    opening = text.index("{", begin)
    depth = 1
    end = opening + 1
    while depth:
        depth += (text[end] == "{") - (text[end] == "}")
        end += 1
    return text[begin:end] + "\n"


def ui_strip(text):
    text = re.sub(r"^use (korangar_interface|rust_state)::.*;\n", "", text, flags=re.M)
    text = text.replace("RustState, ", "").replace(", RustState", "")
    text = text.replace("StateElement, ", "").replace(", StateElement", "")
    text = re.sub(r"^\s*#\[hidden_element\]\n", "\n", text, flags=re.M)
    return text


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkout", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    out = args.output.resolve()
    if out.exists():
        raise SystemExit("output must be a new isolated directory")
    out.mkdir(parents=True)
    provenance = {}

    def read(path):
        data = subprocess.check_output(["git", "-C", str(args.checkout), "show", f"{REVISION}:{path}"])
        provenance[path] = hashlib.sha256(data).hexdigest()
        return data.decode()

    def write(path, text):
        target = out / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)

    prefix = "korangar/src/"
    for name in ("action", "sprite", "animation"):
        write(f"src/loaders/{name}.rs", ui_strip(read(prefix + f"loaders/{name}/mod.rs")))
    for name in ("color", "error"):
        write(f"src/loaders/{name}.rs", read(prefix + f"loaders/{name}.rs"))
    write("src/world/animation.rs", ui_strip(read(prefix + "world/animation/mod.rs")))
    camera = read(prefix + "world/cameras/mod.rs")
    write("src/world/camera.rs", "use std::f32::consts::FRAC_PI_2;\nuse cgmath::{Array, EuclideanSpace, InnerSpace, Matrix4, MetricSpace, Point3, Vector2, Vector3, Vector4};\nuse crate::graphics::ScreenSize;\n" + block(camera, "pub trait Camera") + block(camera, "fn direction("))
    actions = read(prefix + "world/action/mod.rs")
    write("src/world/actions.rs", ui_strip("use korangar_audio::SoundEffectKey;\nuse korangar_container::Cacheable;\nuse ragnarok_formats::action::Action;\n#[derive(Copy, Clone, Debug, Eq, PartialEq, Hash)]\n" + block(actions, "pub enum ActionEvent") + "#[derive(Debug)]\n" + block(actions, "pub struct Actions") + block(actions, "impl Cacheable for Actions")))
    position = read("ragnarok-packets/src/position.rs")
    write("src/direction.rs", "#[derive(Debug, Copy, Clone)]\n" + block(position, "pub enum Direction") + block(position, "impl From<Direction> for u16") + block(position, "impl From<u16> for Direction"))
    entity = read(prefix + "world/entity/mod.rs")
    write("src/entity_type.rs", "#[derive(Debug, Copy, Clone, PartialEq, Eq)]\n" + block(entity, "pub enum EntityType"))
    color = read(prefix + "graphics/color.rs")
    write("src/graphics/color.rs", "use std::ops::Mul;\n#[derive(Debug, Clone, Copy, Default, PartialEq)]\n" + block(color, "pub struct Color") + block(color, "impl Color {") + block(color, "impl Mul<f32> for Color"))
    texture = read(prefix + "graphics/texture.rs")
    imports = texture[:texture.index("use crate::graphics")]
    write("src/graphics/texture.rs", imports + texture[texture.index("static TEXTURE_ID"):texture.index("#[derive(Debug)]\npub struct TextureSet")] + texture[texture.index("pub struct AttachmentTexture {"):texture.index("pub(crate) struct AttachmentTextureFactory")])
    buffer = read(prefix + "graphics/buffer.rs")
    write("src/graphics/buffer.rs", buffer[:buffer.index("use crate::graphics")] + buffer[buffer.index("/// Convenience abstraction"):buffer.index("impl Buffer<u64>")])
    instruction = read(prefix + "graphics/instruction.rs")
    write("src/graphics/instruction.rs", "use std::sync::Arc;\nuse cgmath::{Matrix4, Vector2};\nuse crate::{EntityId, graphics::{Color,Texture}};\n#[derive(Clone,Debug)]\n" + block(instruction, "pub struct EntityInstruction"))
    for name, path in (("entity", "forward/entity.rs"), ("resolve", "postprocessing/wboit_resolve.rs")):
        write(f"src/graphics/{name}.rs", read(prefix + "graphics/passes/" + path))
    gfx = read(prefix + "graphics/mod.rs")
    abi = "use std::num::NonZeroU64;\nuse std::sync::OnceLock;\nuse wgpu::*;\nuse bytemuck::{Pod,Zeroable};\n"
    for name in ("GlobalUniforms", "KernelUniforms", "DirectionalLightUniforms", "DirectionalLightPartition", "PointLightData", "TileLightIndices"):
        abi += "#[derive(Copy,Clone,Pod,Zeroable)]\n#[repr(C)]\n" + block(gfx, f"pub(crate) struct {name}")
    abi = re.sub(r"^(    )(\w+):", r"    pub(crate) \2:", abi, flags=re.M)
    abi += "use super::GlobalContext;\npub const PARTITION_COUNT: usize=3;\nimpl GlobalContext {\n" + block(gfx, "fn global_bind_group_layout(") + block(gfx, "fn forward_bind_group_layout(") + "}\n"
    write("src/graphics/abi.rs", abi.replace("fn global_bind_group_layout", "pub(crate) fn global_bind_group_layout").replace("fn forward_bind_group_layout", "pub(crate) fn forward_bind_group_layout"))
    loader = read(prefix + "loaders/texture/mod.rs")
    write("src/loaders/texture.rs", "use std::sync::Arc;\nuse image::RgbaImage;\nuse wgpu::*;\nuse crate::graphics::Texture;\npub struct TextureLoader {pub device: Arc<Device>,pub queue: Arc<Queue>}\nimpl TextureLoader {\n" + "#[allow(clippy::too_many_arguments)]\n" + block(loader, "    pub fn create_raw_with_data(") + block(loader, "    pub fn create_color(") + "}\n")
    # Read-only diagnostic at the upload boundary; texture construction is unchanged.
    tp = out / "src/loaders/texture.rs"
    tp.write_text(tp.read_text().replace("        Arc::new(texture)", "        crate::walk::record_texture(&texture, width, height, data);\n        Arc::new(texture)"))
    passes = read(prefix + "graphics/passes/mod.rs")
    traits = "use std::marker::ConstParamTy;\nuse wgpu::*;\nuse crate::graphics::{Capabilities,GlobalContext,shader_compiler::ShaderCompiler};\nuse crate::loaders::TextureLoader;\n"
    for name in ("BindGroupCount", "ColorAttachmentCount", "DepthAttachmentCount"):
        traits += "#[derive(Clone,Copy,PartialEq,Eq,ConstParamTy)]\n" + block(passes, f"pub(crate) enum {name}")
    traits += block(passes, "pub(crate) trait RenderPassContext<") + block(passes, "pub(crate) trait Drawer<")
    write("src/graphics/traits.rs", traits)
    for crate in ("korangar-container", "korangar-loaders"):
        paths = subprocess.check_output(["git", "-C", str(args.checkout), "ls-tree", "-r", "--name-only", REVISION, crate]).decode().splitlines()
        for path in paths:
            if "/src/" in path or path.endswith("LICENSE"):
                write("vendor/" + path, read(path))
        deps = '\n[dependencies]\nhashbrown="0.17"\n' if crate.endswith("container") else ""
        write(f"vendor/{crate}/Cargo.toml", f'[package]\nname="{crate}"\nversion="0.1.0"\nedition="2024"\n{deps}\n[features]\ninterface=[]\ndebug=[]\n')
    for crate in ("ragnarok-bytes", "ragnarok-formats", "ragnarok-macros"):
        shutil.copytree(HERE.parent / "rust-oracle/vendor" / crate, out / "vendor" / crate)
    for path in sorted(subprocess.check_output(["git", "-C", str(args.checkout), "ls-tree", "-r", "--name-only", REVISION, "korangar/shaders"]).decode().splitlines()):
        write(path, read(path))
    write("UPSTREAM_LICENSE", read("LICENSE.md"))
    for path in HERE.glob("*.rs"):
        write("src/" + path.name, path.read_text())
    write("Cargo.toml", (HERE / "Cargo.toml").read_text())
    write("Cargo.lock", (HERE / "Cargo.lock").read_text())
    manifest = {"revision": REVISION, "upstream": provenance, "generated": {str(p.relative_to(out)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(out.rglob("*")) if p.is_file()}}
    write("source-manifest.json", json.dumps(manifest, sort_keys=True, indent=2) + "\n")
    print(json.dumps({"revision": REVISION, "upstream_files": len(provenance), "manifest_sha256": hashlib.sha256((out / "source-manifest.json").read_bytes()).hexdigest()}))


if __name__ == "__main__":
    main()
